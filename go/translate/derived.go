package translate

import (
	"encoding/json"
	"fmt"
	"strings"

	"greendrake.nz/go/i18n/negotiate"
	"greendrake.nz/go/i18n/plurals"
	"greendrake.nz/go/translate/internal/files"
)

// Files generated from the shipped set rather than translated: what a host's
// other readers need to know about the locales and cannot work out from the
// manifest themselves. Each is a JSON document whose _comment explains it.

// derivations produce each kind's document, less its comment.
var derivations = map[string]func(m *Manifest) (map[string]any, error){
	// locale_tables is what a browser reads instead of deriving: the plural
	// categories the renderer selects among, and the locale matcher's verdict
	// for every language, script and region a browser can send.
	"locale_tables": func(m *Manifest) (map[string]any, error) {
		negotiator, err := negotiate.New(m.Shipped, m.Default)
		if err != nil {
			return nil, err
		}
		categories := map[string][]string{}
		for _, locale := range m.Shipped {
			categories[locale] = plurals.Categories(locale)
		}
		return map[string]any{"plurals": categories, "languages": negotiator.Table()}, nil
	},
}

// derivedBody is one output's bytes.
func (m *Manifest) derivedBody(d Derived) (string, error) {
	document, err := derivations[d.Kind](m)
	if err != nil {
		return "", err
	}
	comment := []string{fmt.Sprintf("GENERATED by %s from %s.", m.Command, m.file)}
	comment = append(comment, strings.Split(strings.TrimSpace(d.Comment), "\n")...)
	document["_comment"] = comment
	body, err := json.MarshalIndent(document, "", "    ")
	if err != nil {
		return "", err
	}
	return string(body) + "\n", nil
}

// writeDerived emits every derived output into a sink.
func (m *Manifest) writeDerived(sink files.Sink) (changed []string, err error) {
	for _, d := range m.Derived {
		body, err := m.derivedBody(d)
		if err != nil {
			return nil, err
		}
		put, err := sink(m.path(d.Path), body)
		if err != nil {
			return nil, err
		}
		changed = append(changed, put...)
	}
	return changed, nil
}
