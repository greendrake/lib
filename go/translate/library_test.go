// The libraries share one brief, in a file of their own, and each keeps its
// own terms and the glossary they render into: a term of one library is no
// other library's to owe, and a change to the brief owes every library a
// render.
func TestLibrary_SharedBriefOwnGlossary(t *testing.T) {
	project := fixture(t, "de")
	libs := tree(t, map[string]string{
		"translation/brief.yaml":    "brief: A library of user-interface components.\n",
		"translation/register.yaml": fixtureRegister,
	})
	for name, terms := range map[string]string{"a": "terms:\n  listing: An advertisement.\n", "b": "# No terms.\n"} {
		dir := filepath.Join(libs, name)
		require.NoError(t, os.MkdirAll(filepath.Join(dir, "catalogue"), 0o755))
		require.NoError(t, os.MkdirAll(filepath.Join(dir, "translation"), 0o755))
		manifest := []byte(sharedPolicy(libraryManifest))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "translate.yaml"), manifest, 0o644))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "catalogue/en-GB.yaml"), []byte(commonSection), 0o644))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "translation/policy.yaml"), []byte(terms), 0o644))
	}
	c, _ := scriptedClient(t)
	a, b := filepath.Join(libs, "a"), filepath.Join(libs, "b")
	mustRunFor(t, a, project, Options{Client: c})
	mustRunFor(t, b, project, Options{Client: c})
	assert.FileExists(t, filepath.Join(a, "translation/glossary/de.yaml"))
	assert.NoFileExists(t, filepath.Join(b, "translation/glossary/de.yaml"), "b has no terms to render")

	replaceInFile(t, filepath.Join(a, "translation/policy.yaml"), "An advertisement.", "A notice.")
	assert.Equal(t, 1, mustRunFor(t, a, project, Options{Client: c}).Stale["de"], "a's term, re-rendered")
	assert.True(t, mustRunFor(t, b, project, Options{Check: true}).Clean(), "and nothing of b's")

	replaceInFile(t, filepath.Join(libs, "translation/brief.yaml"), "user-interface components", "screens")
	assert.ElementsMatch(t, []string{"gl", "lib"}, mustRunFor(t, a, project, Options{Check: true}).Policy["de"])
	assert.Equal(t, []string{"lib"}, mustRunFor(t, b, project, Options{Check: true}).Policy["de"], "b's vocabulary of no terms owes nothing")
}

// sharedPolicy points a library manifest at the brief and register of the
// directory above it, which the libraries share.
func sharedPolicy(manifest string) string {
	return strings.NewReplacer(
		"brief: translation/brief.yaml", "brief: ../translation/brief.yaml",
		"register: translation/register.yaml", "register: ../translation/register.yaml",
	).Replace(manifest)
}

// Prune keeps the locales of every project serving a library, and removes
// every file of one none of them ships.
func TestPrune_KeepsTheServingProjectsLocales(t *testing.T) {
	german, french := fixture(t, "de"), fixture(t, "fr")
	lib := libraryTree(t)
	c, _ := scriptedClient(t)
	mustRunFor(t, lib, german, Options{Client: c})
	mustRunFor(t, lib, french, Options{Client: c})
	manifest := filepath.Join(lib, "translate.yaml")

	removed, err := Prune(manifest, []*Manifest{load(t, german), load(t, french)})
	require.NoError(t, err)
	assert.Empty(t, removed)

	removed, err = Prune(manifest, []*Manifest{load(t, german)})
	require.NoError(t, err)
	assert.ElementsMatch(t, []string{filepath.Join(lib, "catalogue/fr.yaml"), filepath.Join(lib, "translation/state/fr.yaml")}, removed)
	assert.FileExists(t, filepath.Join(lib, "catalogue/de.yaml"))
	assert.FileExists(t, filepath.Join(lib, "catalogue/en-GB.yaml"), "the master is no locale's to lose")
}

func TestPrune_Refusals(t *testing.T) {
	lib := filepath.Join(libraryTree(t), "translate.yaml")
	_, err := Prune(lib, nil)
	assert.ErrorContains(t, err, "name them")

	project := fixture(t, "de")
	_, err = Prune(filepath.Join(project, "translate.yaml"), []*Manifest{load(t, project)})
	assert.ErrorContains(t, err, "ships its own locales")

	russian := fixture(t, "ru")
	replaceInFile(t, filepath.Join(russian, "translate.yaml"), "default: en-GB", "default: ru")
	replaceInFile(t, filepath.Join(russian, "translation/register.yaml"), "ru: Address the reader as вы.\n", "en-GB: Address the reader plainly.\n")
	_, err = Prune(lib, []*Manifest{load(t, project), load(t, russian)})
	assert.ErrorContains(t, err, "'s master is en-GB and "+filepath.Join(russian, "translate.yaml")+"'s is ru")
}
