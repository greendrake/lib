// A library is run on behalf of each project serving it, in that project's
// locales, and the files a run writes are the same bytes whichever project
// writes them: two projects serving one library read and write the same
// tree, and neither's run disturbs the other's locales.
func TestLibrary_RunForTwoProjectsLeavesEachOthersLocales(t *testing.T) {
	german, french := fixture(t, "de"), fixture(t, "fr")
	lib := libraryTree(t)
	c, _ := scriptedClient(t)

	first := mustRunFor(t, lib, german, Options{Client: c})
	assert.ElementsMatch(t, []string{filepath.Join(lib, "catalogue/de.yaml"), filepath.Join(lib, "translation/state/de.yaml")}, first.Written)
	de := readFile(t, filepath.Join(lib, "catalogue/de.yaml"))
	assert.NotContains(t, de, "bin/demo translate", "the files name no project")
	assert.Contains(t, de, "# GENERATED by the translator over translate.yaml from the en-GB master.")

	second := mustRunFor(t, lib, french, Options{Client: c})
	assert.ElementsMatch(t, []string{filepath.Join(lib, "catalogue/fr.yaml"), filepath.Join(lib, "translation/state/fr.yaml")}, second.Written)
	assert.Zero(t, second.Removed["de"], "German is the other project's, not a de-listed locale")
	assert.Equal(t, de, readFile(t, filepath.Join(lib, "catalogue/de.yaml")))

	for _, project := range []string{german, french} {
		check := mustRunFor(t, lib, project, Options{Check: true})
		assert.True(t, check.Clean(), "%+v", check)
		assert.Len(t, check.Stale, 1, "a check reports the project's own locales alone")
	}
	assert.True(t, mustRunFor(t, lib, german, Options{Client: c}).Clean(), "a run for one project after the other's writes nothing")
}

