// A library's manifest: its master and one catalogue source, run on behalf of
// a project, in its locales.
const libraryManifest = `default: en-GB
state: translation/state
policy:
  path: translation/policy.yaml
  brief: translation/brief.yaml
  register: translation/register.yaml
  glossary: translation/glossary
vocabulary:
  id: gl
  batch: {size: 100}
  tier: strong
  guidance: Each id is a term to render into {language}.
sources:
  - id: lib
    format: yaml-catalogue
    path: catalogue/{locale}.yaml
    syntax: vue-i18n
    markup: html
    batch: {by: first-segment, size: 40}
    tier: fast
    guidance: These are user-interface strings.
`

const commonSection = `common:
    # The label on the primary action.
    submit: Submit
    cancel: Cancel
    greeting: 'Hello, {name}'
    # A plural, vue-i18n style.
    listing_count: '{n} listing | {n} listings'
    linked: 'Welcome to @:brand.name'
`

// libraryTree is a library whose master is the host fixture's common section.
func libraryTree(t *testing.T) string {
	t.Helper()
	return tree(t, map[string]string{
		"translate.yaml":            libraryManifest,
		"catalogue/en-GB.yaml":      commonSection,
		"translation/policy.yaml":   "# No terms.\n",
		"translation/brief.yaml":    "brief: A library of user-interface components.\n",
		"translation/register.yaml": fixtureRegister,
	})
}

// library is the host fixture rendered into German, and a library whose master
// has taken the host's common section over, the host's master without it.
func library(t *testing.T) (host, lib string) {
	t.Helper()
	host = fixture(t, "de")
	mustRun(t, host, Options{Client: german(t)})
	replaceInFile(t, filepath.Join(host, "catalogue/en-GB.yaml"), commonSection, "")
	return host, libraryTree(t)
}

// german renders the host's common strings recognisably.
func german(t *testing.T) llm.Client {
	t.Helper()
	return client(t, func(req llm.Request) (json.RawMessage, error) {
		return echo(t, req, func(id, text string) string {
			if strings.HasPrefix(id, "ui:common.") {
				return "DE " + text
			}
			return text
		})
	})
}

// carry carries for the project fixture at project, each manifest read on its
// behalf where it is a library's.
func carry(t *testing.T, project, from, source, to, target string, carriage Carriage) []string {
	t.Helper()
	p := load(t, project)
	written, err := Carry(loadFor(t, from, p), source, loadFor(t, to, p), target, carriage)
	require.NoError(t, err)
	return written
}

// A move: what the host rendered arrives current, written as the library's
// own run writes it, and the host owes no render at all.
func TestCarry_MovedStringsArriveCurrent(t *testing.T) {
	host, lib := library(t)
	written := carry(t, host, host, "ui", lib, "lib", Carriage{Prefixes: []string{"common."}})
	assert.ElementsMatch(t, []string{filepath.Join(lib, "catalogue/de.yaml"), filepath.Join(lib, "translation/state/de.yaml")}, written)

	germanFile := readFile(t, filepath.Join(lib, "catalogue/de.yaml"))
	assert.Contains(t, germanFile, "submit: DE Submit")
	assert.Contains(t, germanFile, "greeting: DE Hello, {name}")
	assert.Contains(t, germanFile, "# GENERATED by the translator over translate.yaml", "written as the library's own run writes it")

	libraryCheck := mustRunFor(t, lib, host, Options{Check: true})
	assert.True(t, libraryCheck.Clean(), "%+v", libraryCheck)
	assert.Empty(t, libraryCheck.Policy["de"], "a vocabulary of no terms owes nothing under any policy")

	hostCheck := mustRun(t, host, Options{Check: true})
	assert.Zero(t, hostCheck.ToRender())
	assert.Equal(t, unitsOf(t, loadFor(t, lib, load(t, host)), "lib:"), hostCheck.Removed["de"])
}

// Settling asks no model: the host's files and records drop what it no longer
// holds, and the library keeps what it was carried.
func TestSettle_DropsWhatTheMasterNoLongerDefines(t *testing.T) {
	host, lib := library(t)
	carry(t, host, host, "ui", lib, "lib", Carriage{Prefixes: []string{"common."}})

	mustRun(t, host, Options{Settle: true})
	assert.NotContains(t, readFile(t, filepath.Join(host, "catalogue/de.yaml")), "submit")
	assert.True(t, mustRun(t, host, Options{Check: true}).Clean())

	settled := mustRunFor(t, lib, host, Options{Settle: true})
	assert.Zero(t, settled.Stale["de"], "settling renders nothing, and nothing is owed")
	assert.Contains(t, readFile(t, filepath.Join(lib, "catalogue/de.yaml")), "submit: DE Submit")
}

// A string whose text changed on the way is not the string the host
// rendered: it is not carried, and the library owes it.
func TestCarry_ChangedTextIsOwed(t *testing.T) {
	host, lib := library(t)
	replaceInFile(t, filepath.Join(lib, "catalogue/en-GB.yaml"), "submit: Submit", "submit: Send")
	carry(t, host, host, "ui", lib, "lib", Carriage{Prefixes: []string{"common."}})

	assert.NotContains(t, readFile(t, filepath.Join(lib, "catalogue/de.yaml")), "submit:")
	assert.Equal(t, 1, mustRunFor(t, lib, host, Options{Check: true}).Stale["de"])
}

// A key renamed within the host keeps its translation, and the host's files
// are written as a run writes them.
func TestCarry_RenamedKey(t *testing.T) {
	host := fixture(t, "de")
	mustRun(t, host, Options{Client: german(t)})
	replaceInFile(t, filepath.Join(host, "catalogue/en-GB.yaml"), "    submit: Submit\n", "    send: Submit\n")
	carry(t, host, host, "ui", host, "ui", Carriage{Keys: map[string]string{"common.send": "common.submit"}})

	germanFile := readFile(t, filepath.Join(host, "catalogue/de.yaml"))
	assert.Contains(t, germanFile, "send: DE Submit")
	assert.NotContains(t, germanFile, "submit:")
	assert.True(t, mustRun(t, host, Options{Check: true}).Clean())
}

// A new key saying exactly what one the host keeps already says takes the
// host's translation; the host keeps its own.
func TestCarry_CopiedKey(t *testing.T) {
	host, lib := library(t)
	replaceInFile(t, filepath.Join(lib, "catalogue/en-GB.yaml"), commonSection, commonSection+"dialog:\n    dismiss: Cancel\n")
	replaceInFile(t, filepath.Join(host, "catalogue/en-GB.yaml"), "seo:", "common:\n    cancel: Cancel\nseo:")
	carry(t, host, host, "ui", lib, "lib", Carriage{Keys: map[string]string{"dialog.dismiss": "common.cancel"}})

	assert.Contains(t, readFile(t, filepath.Join(lib, "catalogue/de.yaml")), "dismiss: DE Cancel")
	assert.Contains(t, readFile(t, filepath.Join(host, "catalogue/de.yaml")), "cancel: DE Cancel")
}

// A source whose policy moved since it rendered holds nothing: its strings
// are owed a render under the new one.
func TestCarry_SourcePolicyMovedHoldsNothing(t *testing.T) {
	host, lib := library(t)
	replaceInFile(t, filepath.Join(host, "translation/brief.yaml"), "spans the world", "spans the globe")
	written := carry(t, host, host, "ui", lib, "lib", Carriage{Prefixes: []string{"common."}})
	assert.Empty(t, written)
	m := loadFor(t, lib, load(t, host))
	assert.Equal(t, unitsOf(t, m, "lib:"), mustRunManifest(t, m, Options{Check: true}).Stale["de"])
}

// A target whose vocabulary is owed renders every string again once it has
// one, so what arrives is kept as words, not recorded as current.
func TestCarry_TargetVocabularyOwedKeepsWordsOnly(t *testing.T) {
	host, lib := library(t)
	require.NoError(t, os.WriteFile(filepath.Join(lib, "translation/policy.yaml"), []byte("terms:\n  listing: An advertisement.\n"), 0o644))
	carry(t, host, host, "ui", lib, "lib", Carriage{Prefixes: []string{"common."}})

	assert.Contains(t, readFile(t, filepath.Join(lib, "catalogue/de.yaml")), "submit: DE Submit")
	m := loadFor(t, lib, load(t, host))
	assert.Equal(t, unitsOf(t, m, ""), mustRunManifest(t, m, Options{Check: true}).Stale["de"])
}

// A pass carried whole — every key, the empty prefix — from a manifest that
// shipped its own locales to the same pass of a library manifest over the
// same files: what moves is the state, the record of what each translation
// was made from, and the library's check for the project finds nothing owed.
// The files are rewritten under the library's header, which names no
// project.
func TestCarry_PassBetweenManifests(t *testing.T) {
	project := fixture(t, "de")
	libs := tree(t, map[string]string{
		"libs.yaml": `command: bin/demo translate
default: en-GB
shipped: [en-GB, de]
state: translation/state
policy:
  path: translation/policy.yaml
  brief: translation/brief.yaml
  register: translation/register.yaml
  glossary: translation/glossary
vocabulary:
  id: gl
  batch: {size: 100}
  tier: strong
  guidance: Each id is a term to render into {language}.
llm: {env_prefix: TRANSLATE_LLM_, timeout: 10m, parallel: 2}
sources:
  - id: lib
    format: yaml-catalogue
    path: lib/catalogue/{locale}.yaml
    syntax: vue-i18n
    markup: html
    batch: {by: first-segment, size: 40}
    tier: fast
    guidance: These are user-interface strings.
`,
		"translation/policy.yaml":     "# No terms.\n",
		"translation/brief.yaml":      "brief: A library of user-interface components.\n",
		"translation/register.yaml":   fixtureRegister,
		"lib/translate.yaml":          sharedPolicy(libraryManifest),
		"lib/catalogue/en-GB.yaml":    commonSection,
		"lib/translation/policy.yaml": "# No terms.\n",
	})
	c, _ := scriptedClient(t)
	old, err := Load(filepath.Join(libs, "libs.yaml"), nil)
	require.NoError(t, err)
	mustRunManifest(t, old, Options{Client: c})
	require.Contains(t, readFile(t, filepath.Join(libs, "lib/catalogue/de.yaml")), "# GENERATED by bin/demo translate")

	lib := loadFor(t, filepath.Join(libs, "lib"), load(t, project))
	written, err := Carry(old, "lib", lib, "lib", Carriage{Prefixes: []string{""}})
	require.NoError(t, err)
	assert.ElementsMatch(t, []string{filepath.Join(libs, "lib/catalogue/de.yaml"), filepath.Join(libs, "lib/translation/state/de.yaml")}, written)
	assert.Contains(t, readFile(t, filepath.Join(libs, "lib/catalogue/de.yaml")), "# GENERATED by the translator over translate.yaml")
	assert.True(t, mustRunManifest(t, lib, Options{Check: true}).Clean())
}

func TestCarry_Refusals(t *testing.T) {
	cases := map[string]struct {
		source, target string
		carriage       Carriage
		want           string
	}{
		"prefix selects nothing": {"ui", "lib", Carriage{Prefixes: []string{"auth."}}, `lib: the master holds nothing under "auth."`},
		"key not in the target":  {"ui", "lib", Carriage{Keys: map[string]string{"auth.go": "common.submit"}}, "lib: the master holds no auth.go"},
		"nothing named":          {"ui", "lib", Carriage{}, "lib: nothing named to carry"},
		"not a catalogue":        {"tax", "lib", Carriage{Prefixes: []string{"common."}}, "tax is yaml-tree, and only a catalogue's strings are carried"},
		"no such source":         {"ui", "nope", Carriage{Prefixes: []string{"common."}}, "translate.yaml declares no source nope"},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			host, lib := library(t)
			_, err := Carry(load(t, host), tc.source, loadFor(t, lib, load(t, host)), tc.target, tc.carriage)
			assert.ErrorContains(t, err, tc.want)
		})
	}
}

